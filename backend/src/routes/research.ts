import { Router } from 'express'
import { modelStatusForResearch } from '../services/mlClient.js'
import { DEFAULT_THRESHOLDS } from '../services/communityTrends.js'
import { RANKING_WEIGHTS } from '../services/rankingMeta.js'
import { ah } from '../middleware/async.js'

export const researchRouter = Router()

/**
 * Machine-readable research metrics summary (§16 supporting endpoint).
 * It exposes the *documented rules and configuration* plus live model status —
 * it does not fabricate experimental results. Real evaluation numbers come
 * from the ml-service training run (artifacts/metadata.json), reproduced by
 * running `python -m training.train`.
 */
researchRouter.get('/metrics', ah(async (_req, res) => {
  const model = await modelStatusForResearch()
  res.json({
    components: [
      {
        id: 'crop-prediction',
        title: 'Crop prediction pipeline',
        task: model?.taskTitle ?? 'Tabular disease-risk assessment (documented dataset + training script; see ml-service README)',
        modelStatus: model,
        metricsSource: 'ml-service/artifacts/metadata.json — produced by an actual training run; never hand-written',
      },
      {
        id: 'explainability',
        title: 'Explainability (SHAP)',
        method: model.trained ? 'TreeExplainer SHAP over the trained RandomForest' : 'available once model artifacts are trained',
        caveats: 'Feature contributions are associations, not causal proof; displayed with explicit limitations in the app.',
      },
      {
        id: 'treatment-ranking',
        title: 'Cost-aware treatment ranking',
        rule: RANKING_WEIGHTS,
        note: 'Proposed decision rule — treated as a candidate requiring evaluation, not a validated policy.',
      },
      {
        id: 'early-warning',
        title: 'Community early-warning rule',
        thresholds: DEFAULT_THRESHOLDS,
        rule: 'watch/attention require relative elevation over the previous window with minimum-count floors; wording is "potential increase in reported symptoms", never "outbreak".',
      },
    ],
    experimentRepro: {
      train: 'cd ml-service && python -m training.make_fixture && python -m training.train',
      test: 'cd ml-service && pytest -q',
      backendTests: 'cd backend && npm test',
      frontendTests: 'npm test (repo root)',
    },
    honesty: 'Endpoints report configuration and status only. Any accuracy/citation numbers shown in the UI are labelled sample or come from real artifact metadata generated by training runs.',
  })
}))
